import { readFileSync, writeFileSync } from "node:fs";

const SPEC_PATH = new URL("../../backend/openapi.json", import.meta.url);
const OUTPUT_PATH = new URL("../src/app/(app)/api/proxy/[...path]/routes.generated.ts", import.meta.url);

const HTTP_METHODS = ["get", "put", "post", "delete", "options", "head", "patch", "trace"];

const spec = JSON.parse(readFileSync(SPEC_PATH, "utf8"));

const routes = Object.entries(spec.paths ?? {}).flatMap(([path, pathItem]) =>
  HTTP_METHODS.filter((method) => pathItem[method]).map((method) => {
    const { operationId } = pathItem[method];
    if (!operationId) throw new Error(`${method.toUpperCase()} ${path} has no operationId`);
    return { method: method.toUpperCase(), path, operationId };
  }),
);

const operationIds = routes.map((route) => route.operationId);
const duplicate = operationIds.find((operationId, index) => operationIds.indexOf(operationId) !== index);
if (duplicate) throw new Error(`operationId "${duplicate}" is used more than once`);

routes.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));

const rows = routes
  .map((route) => `  { method: "${route.method}", path: "${route.path}", operationId: "${route.operationId}" },`)
  .join("\n");

writeFileSync(OUTPUT_PATH, `/**
 * This file was auto-generated by scripts/generate-proxy-routes.mjs from apps/backend/openapi.json.
 * Do not make direct changes to the file.
 */

export const ROUTES = [
${rows}
] as const;

export type OperationId = (typeof ROUTES)[number]["operationId"];
`);

console.log(`Wrote ${String(routes.length)} proxy routes`);
